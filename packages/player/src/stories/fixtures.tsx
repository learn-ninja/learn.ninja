import * as React from "react"

import bronzeAgeCollapse from "../../../../examples/bronze-age-collapse.json"
import buttonHierarchy from "../../../../examples/button-hierarchy.json"
import compoundInterest from "../../../../examples/compound-interest.json"
import correlationVsCausation from "../../../../examples/correlation-vs-causation.json"
import mapVsForEach from "../../../../examples/map-vs-foreach.json"
import spanishGreetings from "../../../../examples/spanish-greetings.json"
import writingAPrd from "../../../../examples/writing-a-prd.json"

import { validateLesson, type Lesson } from "@workspace/spec"
import { DirectionProvider } from "@workspace/ui/components/direction"

import { PlayerProvider } from "../context"
import type { Prepared } from "../prepared"
import { ariaLocaleFor, stringsFor } from "../strings"
// Generated by `npm run stories:prepare -w @workspace/player` (runs automatically before Storybook starts).
import preparedJson from "./prepared.generated.json"

// Shared data for stories: the example lessons, prepared the same way the web app prepares them.

function load(raw: unknown): Lesson {
  const result = validateLesson(raw)
  if (!result.ok)
    throw new Error("An example lesson is invalid; run the spec tests.")
  return result.lesson
}

export const lessons = {
  buttons: load(buttonHierarchy),
  prd: load(writingAPrd),
  compound: load(compoundInterest),
  spanish: load(spanishGreetings),
  coding: load(mapVsForEach),
  correlation: load(correlationVsCausation),
  bronze: load(bronzeAgeCollapse),
}

export const prepared = preparedJson as Prepared

/** Wraps a story in the player's providers, in the language chosen in the toolbar. */
export function PlayerFrame({
  ui = "en",
  children,
}: {
  ui?: string
  children: React.ReactNode
}) {
  const dir = /^(ar|he|fa|ur)\b/i.test(ui) ? "rtl" : "ltr"
  return (
    <DirectionProvider locale={ariaLocaleFor(ui)}>
      <PlayerProvider
        value={{
          prepared,
          t: stringsFor(ui),
          lang: ui,
          dir,
          visualsCss: "/lesson-visuals.css",
        }}
      >
        <div dir={dir} lang={ui}>
          {children}
        </div>
      </PlayerProvider>
    </DirectionProvider>
  )
}

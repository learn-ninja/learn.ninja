// Measures every country on every region's map, as the player draws it, for the checker: which
// countries a map hotspot can take as answers, and whether each is large enough to tap. Run by
// `npm run map -w @workspace/player` after build-map.ts, and again after changing how a region is
// framed (src/map-frame.ts) or a region's box.

import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import type { Feature, MultiPolygon, Polygon } from "geojson"
import { feature } from "topojson-client"
import type { GeometryCollection, Topology } from "topojson-specification"

import { MAP_REGION_NAMES } from "@workspace/spec"

import data from "../src/map-data.json" with { type: "json" }
import { measureDrawnSizes } from "../src/map-frame"

const topology = data as unknown as Topology<{ countries: GeometryCollection }>
const shapes = feature(topology, topology.objects.countries)
  .features as Feature<Polygon | MultiPolygon>[]
const sizes = MAP_REGION_NAMES.map((region) => {
  const drawn = Object.entries(measureDrawnSizes(region, shapes))
  return `  ${JSON.stringify(region)}: { ${drawn.map(([code, size]) => `${code}: ${size}`).join(", ")} },`
})

const here = (path: string) => fileURLToPath(new URL(path, import.meta.url))
writeFileSync(
  here("../../spec/src/map-sizes.ts"),
  `// Generated by packages/player/scripts/build-map-sizes.ts from the map's shapes. Don't edit.

import type { MapRegion } from "./map"

/**
 * Every country each region's map draws, by ISO alpha-2 code, with how large it's drawn: the larger
 * of its width and height in px at MAP_WIDTH, counting only the part on the map (France's
 * overseas regions, on a map of Africa).
 */
export const DRAWN_SIZES: Record<MapRegion, Record<string, number>> = {
${sizes.join("\n")}
}
`
)
